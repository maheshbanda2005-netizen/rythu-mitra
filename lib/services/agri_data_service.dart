  static List<PriceHistoryPoint> _generateMockPriceHistory(double currentPrice, double trendOffset) {
    final List<PriceHistoryPoint> points = [];
    double base = currentPrice - (trendOffset * 10);
    for (int i = 30; i >= 1; i--) {
      final variation = ((i % 5) - 2) * (currentPrice * 0.015);
      final price = base + ((30 - i) / 30.0) * (currentPrice - base) + variation;
      points.add(PriceHistoryPoint(
        day: 31 - i,
        price: double.parse(price.toStringAsFixed(1)),
        dateLabel: '${31 - i} Aug',
      ));
    }
    return points;
  }

